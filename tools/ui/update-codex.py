#!/usr/bin/env python3
"""Vendor the pinned Wikimedia Codex styles used by the CLI's Go-rendered pages."""

import base64
import hashlib
import io
from pathlib import Path
import subprocess
import tarfile
import urllib.request


VERSION = "2.7.0"
DESTINATION = Path(__file__).resolve().parents[2] / "mount/dev/compose/base/mount/ui"
PACKAGES = {
    "codex": (
        "LZvhmGd2YcKKkavJVkWUVDL/aoBJRcSMO+PeEr5J5r4ieEye3nrtdZIuDygTezoKrLWMDNP9zUJG9kBmqzdUvw==",
        {"dist/codex.style.css": "codex.style.css", "LICENSE": "LICENSE.codex"},
    ),
    "codex-design-tokens": (
        "wdvIzDKQmmRkVi/YYyAO0ufXYz1ISJUYzLNKWP13QlBrkw/Y6z0dypOm4WA2vJNgNxTmiabOA3dLFvefLinylQ==",
        {
            "theme-wikimedia-ui.css": "tokens.css",
            "theme-wikimedia-ui-mode-dark.css": "tokens-dark.css",
            "LICENSE": "LICENSE.codex-design-tokens",
        },
    ),
}


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    link_mixin = ""
    token_definitions = ""
    for package, (checksum, files) in PACKAGES.items():
        url = f"https://registry.npmjs.org/@wikimedia/{package}/-/{package}-{VERSION}.tgz"
        with urllib.request.urlopen(url, timeout=60) as response:
            archive = response.read()
        if base64.b64encode(hashlib.sha512(archive).digest()).decode() != checksum:
            raise ValueError(f"Unexpected integrity for {package} {VERSION}")
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
            if package == "codex":
                link_mixin = tar.extractfile("package/mixins/link.less").read().decode()
            else:
                token_definitions = tar.extractfile("package/theme-wikimedia-ui.less").read().decode()
            for source, target in files.items():
                with tar.extractfile(f"package/{source}") as asset:
                    (DESTINATION / target).write_bytes(asset.read())
                print(f"{package} {VERSION}: {target}")
    # Link is an official Less mixin rather than part of codex.style.css.
    compiled = subprocess.run(
        ["node", str(Path(__file__).with_name("compile-links.cjs"))],
        input=token_definitions + "\n" + link_mixin + "\n.cdx-link { .cdx-mixin-link(); }\n",
        capture_output=True,
        text=True,
        check=True,
    )
    (DESTINATION / "codex-links.css").write_text(
        f"/* Wikimedia Codex {VERSION} Link mixin; generated by tools/ui/update-codex.py. */\n"
        + compiled.stdout
    )
    print(f"codex {VERSION}: codex-links.css")


if __name__ == "__main__":
    main()
