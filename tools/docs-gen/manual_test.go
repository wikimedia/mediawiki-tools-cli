func TestManualLinksFlagsAndRegeneration(t *testing.T) {
	root := &cobra.Command{Use: "mw", Short: "CLI", DisableAutoGenTag: true}
	wiki := &cobra.Command{Use: "wiki", Short: "Wiki commands"}
	wiki.PersistentFlags().String("profile", "", "Saved profile")
	page := &cobra.Command{Use: "page", Short: "Manage pages"}
	put := &cobra.Command{Use: "put", Short: "Save a page", Example: "mw wiki page put --title Test", Run: func(*cobra.Command, []string) {}}
	put.Flags().String("title", "", "Page title")
	page.AddCommand(put, &cobra.Command{Use: "hidden", Hidden: true})
	page.AddCommand(&cobra.Command{Use: "index", Short: "List indexes", Run: func(*cobra.Command, []string) {}})
	wiki.AddCommand(page)
	root.AddCommand(wiki)
	directory := t.TempDir()
	version := documentationVersion{Label: "v2026.11.15.0"}
	if err := writeManual(root, directory, version); err != nil {
		t.Fatal(err)
	}
	filename := filepath.Join(directory, "wiki", "page", "put", "index.md")
	data, err := os.ReadFile(filename)
	if err != nil {
		t.Fatal(err)
	}
	for _, expected := range []string{"title: \"mw wiki page put\"", "v2026.11.15.0", "--title", "--profile", "Global options", "](/manual/wiki/page/)", manualMarker} {
		if !strings.Contains(string(data), expected) {
			t.Fatalf("manual missing %q", expected)
		}
	}
	if strings.Contains(string(data), "Auto generated by") {
		t.Fatal("manual contains a nondeterministic generation timestamp")
	}
	if _, err := os.Stat(filepath.Join(directory, "wiki", "page", "index", "index.md")); err != nil {
		t.Fatal("literal index command lost its own page")
	}
	before, _ := os.Stat(filename)
	if err := writeManual(root, directory, version); err != nil {
		t.Fatal(err)
	}
	after, _ := os.Stat(filename)
	if !before.ModTime().Equal(after.ModTime()) {
		t.Fatal("unchanged help would trigger live reload")
	}
	notes := filepath.Join(directory, "notes.md")
	if err := os.WriteFile(notes, []byte("hand-written notes"), 0o644); err != nil {
		t.Fatal(err)
	}
	page.RemoveCommand(put)
	if err := writeManual(root, directory, version); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filename); !os.IsNotExist(err) {
		t.Fatal("removed command page retained")
	}
	if _, err := os.Stat(notes); err != nil {
		t.Fatal("regeneration removed a hand-written page")
	}
	if err := os.WriteFile(filepath.Join(directory, "index.md"), []byte("hand-written page"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writeManual(root, directory, version); err == nil || !strings.Contains(err.Error(), "hand-written") {
		t.Fatal("hand-written page was overwritten")
	}
}

func TestManualUsesHelpGroups(t *testing.T) {
	root := &cobra.Command{Use: "mw", DisableAutoGenTag: true}
	root.AddGroup(&cobra.Group{ID: "dev", Title: "Development Commands"}, &cobra.Group{ID: "service", Title: "Service Commands"})
	run := func(*cobra.Command, []string) {}
	root.AddCommand(
		&cobra.Command{Use: "zdev", GroupID: "dev", Run: run},
		cobrautil.WithServiceInfo(&cobra.Command{Use: "api", GroupID: "service", Run: run}, cobrautil.ServiceInfo{Name: "Example API", URL: "https://example.org", Logo: "https://example.org/logo.svg"}),
		&cobra.Command{Use: "config", Run: run},
		&cobra.Command{Use: "hidden", GroupID: "service", Hidden: true, Run: run},
		&cobra.Command{Use: "old", Deprecated: "Use config", Run: run},
	)
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	directory := t.TempDir()
	if err := writeManual(root, directory, documentationVersion{}); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(directory, "_meta.json"))
	if err != nil {
		t.Fatal(err)
	}
	var metadata manualMetadata
	if err := json.Unmarshal(data, &metadata); err != nil {
		t.Fatal(err)
	}
	if len(metadata.Sidebar) != 3 {
		t.Fatalf("sidebar groups: %+v", metadata.Sidebar)
	}
	if len(metadata.Services) != 1 || metadata.Services[0].Name != "Example API" || metadata.Services[0].Link != "/manual/api/" || metadata.Services[0].Development || metadata.Services[0].URL != "https://example.org" || metadata.Services[0].Logo != "https://example.org/logo.svg" {
		t.Fatalf("service catalog must use visible commands and their metadata: %+v", metadata.Services)
	}
	for i, title := range []string{"Development", "Services", "Other"} {
		if metadata.Sidebar[i].Label != title {
			t.Fatalf("group %d: %s", i, metadata.Sidebar[i].Label)
		}
	}
	if metadata.Sidebar[0].Items[0].Label != "zdev" || len(metadata.Sidebar[1].Items) != 1 {
		t.Fatal("commands not grouped or hidden command included")
	}
	data, err = os.ReadFile(filepath.Join(directory, "index.md"))
	if err != nil {
		t.Fatal(err)
	}
	content := string(data)
	previous := -1
	for _, title := range []string{"Development", "Services", "Other"} {
		index := strings.Index(content, "## "+title)
		if index <= previous {
			t.Fatalf("missing or out-of-order group %s", title)
		}
		previous = index
	}
	for _, name := range []string{"help", "completion"} {
		if !strings.Contains(content, "](/manual/"+name+"/)") {
			t.Fatalf("missing %s link", name)
		}
		if _, err := os.Stat(filepath.Join(directory, name, "index.md")); err != nil {
			t.Fatal(err)
		}
	}
	if strings.Contains(content, "](/manual/hidden/)") || strings.Contains(content, "](/manual/old/)") {
		t.Fatal("unavailable commands included")
	}
}

func TestManualWebLayout(t *testing.T) {
	root := &cobra.Command{Use: "mw"}
	root.PersistentFlags().String("profile", "", "Saved profile")
	command := &cobra.Command{Use: "login", Short: "Short description", Long: "A longer description.", Example: "  mw login --name example\n  if true; then\n    mw login --name other\n  fi", Run: func(*cobra.Command, []string) {}}
	command.Flags().StringP("name", "n", "example", "Name <value> & description")
	command.Flags().Bool("hidden", false, "Not public")
	if err := command.Flags().MarkHidden("hidden"); err != nil {
		t.Fatal(err)
	}
	root.AddCommand(command)
	content := manualContent(command)
	for _, expected := range []string{"```text\nmw login [flags]", "A longer description.", "## Options", "## Global options", "<dl", "-n, --name &lt;string&gt;", "Name &lt;value&gt; &amp; description", "Default: <code>example</code>", "## Examples", "```sh\nmw login --name example\nif true; then\n  mw login --name other\nfi\n```", "## See also", "](/manual/)"} {
		if !strings.Contains(content, expected) {
			t.Fatalf("missing %q in %s", expected, content)
		}
	}
	for _, unwanted := range []string{"Synopsis", "SEE ALSO", "Short description", "--hidden", "Options inherited from parent commands"} {
		if strings.Contains(content, unwanted) {
			t.Fatalf("unexpected %q", unwanted)
		}
	}
}

func TestManualDevelopmentNavigation(t *testing.T) {
	root := &cobra.Command{Use: "mw", DisableAutoGenTag: true}
	root.AddGroup(&cobra.Group{ID: "dev", Title: "Development Commands"})
	dev := &cobra.Command{Use: "dev", GroupID: "dev"}
	dev.AddGroup(&cobra.Group{ID: "service", Title: "Service Commands"})
	service := &cobra.Command{Use: "mediawiki", GroupID: "service"}
	service.AddCommand(&cobra.Command{Use: "create", Run: func(*cobra.Command, []string) {}})
	dev.AddCommand(service)
	root.AddCommand(dev)
	directory := t.TempDir()
	if err := writeManual(root, directory, documentationVersion{}); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(directory, "_meta.json"))
	if err != nil {
		t.Fatal(err)
	}
	var metadata manualMetadata
	if err := json.Unmarshal(data, &metadata); err != nil {
		t.Fatal(err)
	}
	mainDev := metadata.Sidebar[0].Items[0]
	if mainDev.Link != "/manual/dev/" || len(mainDev.Items) != 0 {
		t.Fatal("main sidebar expands the development command tree")
	}
	serviceItem := metadata.DevelopmentSidebar[0].Items[0]
	if serviceItem.Label != "mediawiki" || serviceItem.Link != "/manual/dev/mediawiki/" || len(serviceItem.Items) != 0 {
		t.Fatalf("development sidebar should link to service overviews: %+v", serviceItem)
	}
	if len(metadata.Services) != 1 || !metadata.Services[0].Development || metadata.Services[0].Link != "/manual/dev/mediawiki/" {
		t.Fatalf("development services must come from the dev command: %+v", metadata.Services)
	}
	found := false
	for _, command := range metadata.Commands {
		if command.Link == "/manual/dev/mediawiki/create/" {
			found = command.Name == "create" && command.Parent == "/manual/dev/mediawiki/"
		}
	}
	if !found {
		t.Fatal("command navigation lost the create command or its parent")
	}
}

func TestServiceChildrenUseVisibleAnnotatedCommands(t *testing.T) {
	service := &cobra.Command{Use: "tools"}
	tool := cobrautil.WithServiceInfo(&cobra.Command{Use: "example", Run: func(*cobra.Command, []string) {}}, cobrautil.ServiceInfo{Name: "Example tool", URL: "https://example.org", Logo: "https://example.org/favicon.ico"})
	service.AddCommand(tool,
		&cobra.Command{Use: "ordinary", Run: func(*cobra.Command, []string) {}},
		cobrautil.WithServiceInfo(&cobra.Command{Use: "hidden", Hidden: true}, cobrautil.ServiceInfo{Name: "Hidden tool"}),
	)
	root := &cobra.Command{Use: "mw"}
	root.AddCommand(service)
	reference := manualServiceReference(service, false)
	if len(reference.Children) != 1 || reference.Children[0].Name != "Example tool" || reference.Children[0].Link != "/manual/tools/example/" || reference.Children[0].Logo != "https://example.org/favicon.ico" {
		t.Fatalf("service children should follow visible annotated commands: %+v", reference.Children)
	}
}
