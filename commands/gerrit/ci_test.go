func runCITest(t *testing.T, args ...string) (string, string, error) {
	t.Helper()
	cmd := NewGerritCmd()
	var stdout, stderr bytes.Buffer
	cmd.SetOut(&stdout)
	cmd.SetErr(&stderr)
	cmd.SetArgs(append([]string{"ci"}, args...))
	err := cmd.ExecuteContext(t.Context())
	return stdout.String(), stderr.String(), err
}

func useCITestTransport(t *testing.T, change, queue string) {
	t.Helper()
	old := http.DefaultTransport
	t.Cleanup(func() { http.DefaultTransport = old })
	http.DefaultTransport = transportFunc(func(req *http.Request) (*http.Response, error) {
		if req.Header.Get("Authorization") != "" {
			t.Fatal("public CI request used credentials")
		}
		status, body := http.StatusOK, ""
		switch req.URL.Host + req.URL.Path {
		case "gerrit.wikimedia.org/r/changes/":
			if !strings.HasPrefix(req.URL.Query().Get("q"), "commit:") {
				t.Fatalf("expected a commit query, got %s", req.URL)
			}
			body = ")]}'\n" + `[{"_number":1372985}]`
		case "gerrit.wikimedia.org/r/changes/1372985/detail":
			body = ")]}'\n" + change
		case "integration.wikimedia.org/zuul/status.json":
			body = queue
			if queue == "" {
				status = http.StatusServiceUnavailable
			}
		case "integration.wikimedia.org/ci/job/phan/7/consoleText":
			body = "FAILED: Phan\n"
		default:
			t.Fatalf("unexpected request for %s", req.URL)
		}
		return &http.Response{StatusCode: status, Header: make(http.Header), Body: io.NopCloser(strings.NewReader(body)), Request: req}, nil
	})
}

func TestCIStatusFromPatchsetURL(t *testing.T) {
	setupAuthTest(t)
	credential := config.Credential{Key: "gerrit.password", Service: "gerrit", Endpoint: secrets.GerritEndpoint, Account: "fixture"}
	if err := credential.SaveWithMetadata("fixture-secret", false, map[string]string{"gerrit.username": "fixture"}); err != nil {
		t.Fatal(err)
	}
	keyring.MockInitWithError(errors.New("locked"))
	useCITestTransport(t, ciTestChange, ciTestQueue)

	data, stderr, err := runCITest(t, "status", "https://gerrit.wikimedia.org/r/c/mediawiki/core/+/1372985/2", "--output", "json")
	if err != nil || stderr != "" {
		t.Fatalf("status failed: %v, stderr %q", err, stderr)
	}
	var result ciSnapshot
	if err := json.Unmarshal([]byte(data), &result); err != nil {
		t.Fatal(err)
	}
	if result.Patchset != 2 || !result.QueueAvailable || len(result.Jobs) != 4 {
		t.Fatalf("unexpected snapshot: %+v", result)
	}
	want := []ciJob{
		{Pipeline: "test", Name: "composer", Status: "UNSTABLE", NonVoting: true, Duration: "10s", BuildURL: "https://integration.wikimedia.org/ci/job/composer/8/"},
		{Pipeline: "test", Name: "phan", Status: "FAILURE", Duration: "1m 49s", BuildURL: "https://integration.wikimedia.org/ci/job/phan/7/"},
		{Pipeline: "test", Name: "node", Status: "QUEUED", Active: true},
		{Pipeline: "test", Name: "phan", Status: "RUNNING", Active: true, BuildURL: "https://integration.wikimedia.org/ci/job/phan/10/"},
	}
	for i := range want {
		if result.Jobs[i] != want[i] {
			t.Errorf("job %d = %+v, want %+v", i, result.Jobs[i], want[i])
		}
	}
}

func TestCILogsUsesReportedBuildWhenZuulIsUnavailable(t *testing.T) {
	useCITestTransport(t, ciTestChange, "")
	_, _, err := runCITest(t, "logs", "1372985", "--patchset", "2")
	if err == nil || !strings.Contains(err.Error(), "composer (test), phan (test)") {
		t.Fatalf("expected ambiguous log selection, got %v", err)
	}
	log, _, err := runCITest(t, "logs", "1372985", "--patchset", "2", "--job", "phan")
	if err != nil || log != "FAILED: Phan\n" {
		t.Fatalf("logs = %q, %v", log, err)
	}
	status, stderr, err := runCITest(t, "status", "1372985", "--patchset", "2")
	if err != nil || !strings.Contains(status, "FAILURE") || !strings.Contains(stderr, "Zuul live status unavailable") {
		t.Fatalf("status = %q, stderr = %q, err = %v", status, stderr, err)
	}
}

func TestCIStatusFromCheckoutUsesMatchingPatchset(t *testing.T) {
	dir := t.TempDir()
	git := func(args ...string) string {
		t.Helper()
		cmd := osexec.CommandContext(t.Context(), "git", args...)
		cmd.Dir = dir
		result, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, result)
		}
		return strings.TrimSpace(string(result))
	}
	git("init", "--quiet")
	git("-c", "user.name=CI Test", "-c", "user.email=ci@example.org",
		"-c", "commit.gpgsign=false", "commit", "--quiet", "--allow-empty", "-m", "fixture")
	head := git("rev-parse", "HEAD")
	change := strings.Replace(ciTestChange, "older-sha", head, 1)
	useCITestTransport(t, change, ciTestQueue)
	// Run Git from a fixture checkout without touching the source worktree.
	t.Chdir(dir)
	data, _, err := runCITest(t, "status", "--output", "jq", "--format", ".patchset")
	if err != nil || strings.TrimSpace(data) != "2" {
		t.Fatalf("checkout status = %q, %v (HEAD %s)", data, err, head)
	}
}

func TestCIRejectsUntrustedBuildLinks(t *testing.T) {
	for _, address := range []string{
		"https://example.org/ci/job/phan/7/console",
		"https://integration.wikimedia.org/ci/job/../job/phan/7/console",
		"https://integration.wikimedia.org/ci/job/phan/7/console/admin",
	} {
		if _, build := ciBuild(address); build != "" {
			t.Errorf("accepted unsafe build URL %q", address)
		}
	}
}
