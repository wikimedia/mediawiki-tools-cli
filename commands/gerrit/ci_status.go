const (
	ciIntegrationHost = "integration.wikimedia.org"
	ciZuulStatusURL   = "https://" + ciIntegrationHost + "/zuul/status.json"
	ciBotAccount      = 75 // Wikimedia's jenkins-bot Gerrit account
)

var (
	ciBuildPath  = regexp.MustCompile(`^/ci/(?:job/([A-Za-z0-9_.-]+)/)+([0-9]+)(?:/console(?:Full)?)?/?$`)
	ciReportLine = regexp.MustCompile(`^\s*-\s+(\S+)\s+:\s+(\S+)(?: in ([^(]+?))?(?: (\(non-voting\)))?\s*$`)
)

type ciTarget struct {
	change   int
	patchset int
	commit   string
}

type ciSnapshot struct {
	Change         int     `json:"change"`
	Patchset       int     `json:"patchset"`
	Project        string  `json:"project"`
	QueueAvailable bool    `json:"queue_available"`
	Jobs           []ciJob `json:"jobs"`
}

type ciJob struct {
	Pipeline  string `json:"pipeline"`
	Name      string `json:"name"`
	Status    string `json:"status"`
	Active    bool   `json:"active"`
	NonVoting bool   `json:"non_voting"`
	Duration  string `json:"duration,omitempty"`
	BuildURL  string `json:"build_url,omitempty"`
}

func selectCITarget(ctx context.Context, args []string, patchset int) (ciTarget, error) {
	target := ciTarget{patchset: patchset}
	var err error
	if len(args) == 0 {
		head, err := osexec.CommandContext(ctx, "git", "rev-parse", "--verify", "HEAD").Output()
		if err != nil {
			return target, fmt.Errorf("cannot read Git HEAD. Pass a Gerrit change number or URL")
		}
		target.commit = strings.TrimSpace(string(head))
		return target, nil
	}
	target.change, target.patchset, err = parseGerritChange(args[0], patchset)
	return target, err
}

func (target *ciTarget) resolveChange(ctx context.Context, client *gogerrit.Client) error {
	if target.change != 0 {
		return nil
	}
	changes, _, err := client.Changes.QueryChanges(ctx, &gogerrit.QueryChangeOptions{
		QueryOptions: gogerrit.QueryOptions{Query: []string{"commit:" + target.commit}, Limit: 2},
	})
	if err != nil {
		return fmt.Errorf("look up Git HEAD in Gerrit: %w", err)
	}
	if len(*changes) != 1 || (*changes)[0].MoreChanges {
		return fmt.Errorf("Git HEAD did not match exactly one public Gerrit change. Pass a change number or URL")
	}
	target.change = (*changes)[0].Number
	return nil
}

func (target ciTarget) readChange(ctx context.Context, client *gogerrit.Client) (*gogerrit.ChangeInfo, int, error) {
	field := "CURRENT_REVISION"
	if target.patchset != 0 || target.commit != "" {
		field = "ALL_REVISIONS"
	}
	change, _, err := client.Changes.GetChangeDetail(ctx, strconv.Itoa(target.change), &gogerrit.ChangeOptions{
		AdditionalFields: []string{field},
	})
	if err != nil {
		return nil, 0, fmt.Errorf("read Gerrit change %d: %w", target.change, err)
	}
	patchset := target.patchset
	if patchset == 0 && target.commit != "" {
		patchset = change.Revisions[target.commit].Number
		if patchset == 0 {
			return nil, 0, fmt.Errorf("Git HEAD is not a patchset of Gerrit change %d. Pass a change number or URL", target.change)
		}
	}
	if patchset == 0 {
		patchset = change.CurrentRevisionNumber
		if patchset == 0 {
			_, revision, _ := gerritapi.Revision(change, 0)
			patchset = revision.Number
		}
	}
	if patchset > 0 && patchset == change.CurrentRevisionNumber {
		return change, patchset, nil
	}
	if _, _, ok := gerritapi.Revision(change, patchset); patchset > 0 && ok {
		return change, patchset, nil
	}
	return nil, 0, fmt.Errorf("patchset %d is unavailable for Gerrit change %d", patchset, target.change)
}

func ciBuild(raw string) (string, string) {
	address, err := url.Parse(raw)
	if err != nil || address.Scheme != "https" || address.Host != ciIntegrationHost || address.User != nil {
		return "", ""
	}
	match := ciBuildPath.FindStringSubmatch(address.Path)
	if match == nil || match[1] == "." || match[1] == ".." {
		return "", ""
	}
	path := strings.TrimRight(address.Path, "/")
	path = strings.TrimSuffix(strings.TrimSuffix(path, "/consoleFull"), "/console")
	for _, segment := range strings.Split(path, "/") {
		if segment == "." || segment == ".." {
			return "", ""
		}
	}
	return match[1], "https://" + ciIntegrationHost + path + "/"
}

// Each completed report replaces the previous attempt for its pipeline.
// Start notices have no result rows and leave the previous report visible.
func reportedCIJobs(messages []gogerrit.ChangeMessageInfo, patchset int) []ciJob {
	reports := make(map[string][]ciJob)
	for _, message := range messages {
		const prefix = "autogenerated:ci-"
		if message.RevisionNumber != patchset || message.Author.AccountID != ciBotAccount || !strings.HasPrefix(message.Tag, prefix) {
			continue
		}
		pipeline := strings.TrimPrefix(message.Tag, prefix)
		var jobs []ciJob
		for _, line := range strings.Split(message.Message, "\n") {
			match := ciReportLine.FindStringSubmatch(line)
			if match == nil {
				continue
			}
			name, build := ciBuild(match[1])
			if build == "" {
				continue
			}
			jobs = append(jobs, ciJob{
				Pipeline: pipeline, Name: name, Status: match[2], NonVoting: match[4] != "",
				Duration: strings.TrimSpace(match[3]), BuildURL: build,
			})
		}
		if len(jobs) != 0 {
			reports[pipeline] = jobs
		}
	}
	jobs := []ciJob{}
	for _, report := range reports {
		jobs = append(jobs, report...)
	}
	return jobs
}

type zuulStatus struct {
	Pipelines []struct {
		Name   string `json:"name"`
		Queues []struct {
			Heads [][]struct {
				ID   string `json:"id"`
				Live bool   `json:"live"`
				Jobs []struct {
					Name   string `json:"name"`
					Result string `json:"result"`
					URL    string `json:"url"`
					Queued bool   `json:"queued"`
					Voting bool   `json:"voting"`
				} `json:"jobs"`
			} `json:"heads"`
		} `json:"change_queues"`
	} `json:"pipelines"`
}

func readCIQueue(ctx context.Context, change, patchset int) ([]ciJob, error) {
	resp, err := getCIIntegration(ctx, ciZuulStatusURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	var queue zuulStatus
	if err := json.NewDecoder(io.LimitReader(resp.Body, 16<<20)).Decode(&queue); err != nil {
		return nil, fmt.Errorf("decode Zuul status: %w", err)
	}
	if queue.Pipelines == nil {
		return nil, fmt.Errorf("Zuul status did not include pipelines")
	}

	id := fmt.Sprintf("%d,%d", change, patchset)
	var jobs []ciJob
	for _, pipeline := range queue.Pipelines {
		for _, queue := range pipeline.Queues {
			for _, head := range queue.Heads {
				for _, item := range head {
					if item.ID != id || !item.Live {
						continue
					}
					for _, job := range item.Jobs {
						status := job.Result
						switch {
						case status != "":
						case job.Queued:
							status = "QUEUED"
						case job.URL != "":
							status = "RUNNING"
						default:
							status = "PENDING"
						}
						_, build := ciBuild(job.URL)
						jobs = append(jobs, ciJob{
							Pipeline: pipeline.Name, Name: job.Name, Status: status,
							Active: true, NonVoting: !job.Voting, BuildURL: build,
						})
					}
				}
			}
		}
	}
	return jobs, nil
}

func getCIIntegration(ctx context.Context, address string) (*http.Response, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, address, nil)
	if err != nil {
		return nil, err
	}
	client := cli.NewHTTPClient()
	client.CheckRedirect = func(req *http.Request, via []*http.Request) error {
		if req.URL.Scheme != "https" || req.URL.Host != ciIntegrationHost || req.URL.User != nil || len(via) >= 10 {
			return http.ErrUseLastResponse
		}
		return nil
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("%s returned HTTP %d", address, resp.StatusCode)
	}
	return resp, nil
}

func captureCIStatus(ctx context.Context, client *gogerrit.Client, target ciTarget) (ciSnapshot, error, error) {
	change, patchset, err := target.readChange(ctx, client)
	if err != nil {
		return ciSnapshot{}, nil, err
	}
	jobs := reportedCIJobs(change.Messages, patchset)
	builds := make(map[string]bool, len(jobs))
	for _, job := range jobs {
		builds[job.BuildURL] = true
	}
	active, queueErr := readCIQueue(ctx, target.change, patchset)
	for _, job := range active {
		if job.BuildURL == "" || !builds[job.BuildURL] {
			jobs = append(jobs, job)
		}
	}
	slices.SortStableFunc(jobs, func(a, b ciJob) int {
		if order := strings.Compare(a.Pipeline, b.Pipeline); order != 0 {
			return order
		}
		if a.failed() != b.failed() {
			if a.failed() {
				return -1
			}
			return 1
		}
		return strings.Compare(a.Name, b.Name)
	})
	return ciSnapshot{
		Change: target.change, Patchset: patchset, Project: change.Project,
		QueueAvailable: queueErr == nil, Jobs: jobs,
	}, queueErr, nil
}

func (job ciJob) failed() bool {
	switch job.Status {
	case "FAILURE", "UNSTABLE", "ABORTED", "LOST", "ERROR", "TIMED_OUT":
		return true
	default:
		return false
	}
}
